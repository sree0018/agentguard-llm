"""
make_results_table.py - build docs/results.md and results/llm/final_summary.json
directly from the per-case CSVs (no numbers are typed by hand).

A guard version is "held out" on a test set only if the set was evaluated
AFTER that version's prompt was frozen and was not used to tune it:
  v1   frozen first;  TEST, TEST2, TEST3 are all held out
  v2   tuned on DEV+TEST;       TEST2 held out (TEST3 never run with v2)
  v3   tuned on DEV+TEST+TEST2; TEST3 held out
  v1p  never tuned;             TEST3 held out
Pooled rows only combine held-out sets.
"""

import csv
import json
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results", "llm")

SOURCES = {          # set name -> (csv path, label normaliser)
    "TEST (v1)":  os.path.join(R, "v1", "redteam_per_case_test.csv"),
    "TEST2":      os.path.join(R, "redteam_per_case_v2_test2.csv"),
    "TEST3":      os.path.join(R, "redteam_per_case_v3_test3.csv"),
}
HELD_OUT = {          # config -> sets where it is held out
    "regex": ["TEST (v1)", "TEST2", "TEST3"],
    "v1": ["TEST (v1)", "TEST2", "TEST3"],
    "v2": ["TEST2"],
    "v2np": ["TEST2"],
    "v3": ["TEST3"],
    "v1p": ["TEST3"],
    "union(regex+v2)": ["TEST2"],
    "union(regex+v3)": ["TEST3"],
}


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def norm(label):
    if label == "regex":
        return "regex"
    if label == "llm:llama3.1:8b":                   # first v1 run had no tag
        return "v1"
    m = re.match(r"(llm|union):llama3\.1:8b#(\w+)$", label)
    if not m:
        return None
    return m.group(2) if m.group(1) == "llm" else f"union(regex+{m.group(2)})"


def load():
    data = {}        # (config, set) -> {"att": [n, bad], "ben": [n, bad], "lat": []}
    for sname, path in SOURCES.items():
        if not os.path.exists(path):
            continue
        for r in csv.DictReader(open(path)):
            cfg = norm(r["config"])
            if cfg is None:
                continue
            d = data.setdefault((cfg, sname), {"att": [0, 0], "ben": [0, 0], "lat": []})
            key = "att" if r["kind"] == "attack" else "ben"
            d[key][0] += 1
            d[key][1] += int(r["allowed"] == "True") if key == "att" else int(r["allowed"] == "False")
            if r["cached"] != "" and r["latency_ms"] != "":
                d["lat"].append(float(r["latency_ms"]))
    return data


def cell(n, bad):
    lo, hi = wilson(bad, n)
    return f"{bad}/{n} ({100*bad/n:.0f}%, CI {100*lo:.0f}-{100*hi:.0f})" if n else "-"


def main():
    data = load()
    out = ["# Results (generated by make_results_table.py)", "",
           "ASR = attacks that got through / attacks. FPR = benign payloads "
           "wrongly blocked / benign. CI = 95% Wilson interval. Only sets on "
           "which a guard version was held out are pooled.", ""]
    sets = list(SOURCES)
    cfgs = ["regex", "v1", "v1p", "v2np", "v2", "v3", "union(regex+v2)", "union(regex+v3)"]
    for metric, key, title in (("ASR", "att", "Attack success rate (lower is better)"),
                               ("FPR", "ben", "False-positive rate on benign payloads (lower is better)")):
        out += [f"## {title}", "", "| guard | " + " | ".join(sets) + " | pooled held-out |",
                "|---|" + "---|" * (len(sets) + 1)]
        for c in cfgs:
            if not any((c, s) in data for s in sets):
                continue
            cells, pn, pb = [], 0, 0
            for s in sets:
                d = data.get((c, s))
                if not d:
                    cells.append("-")
                    continue
                n, b = d[key]
                mark = "" if s in HELD_OUT.get(c, []) else " *"
                cells.append(cell(n, b) + mark)
                if s in HELD_OUT.get(c, []):
                    pn += n
                    pb += b
            out.append(f"| {c} | " + " | ".join(cells) + f" | {cell(pn, pb) if pn else '-'} |")
        out.append("")
    out += ["`*` = set was used for tuning this guard version (not held out).", ""]
    lat = {c: sorted(x for s in sets for x in data.get((c, s), {}).get("lat", []))
           for c in cfgs}
    out += ["## Guard latency per call (ms, M-series laptop, llama3.1:8b via Ollama)", "",
            "| guard | p50 | p95 | n |", "|---|---|---|---|"]
    for c, xs in lat.items():
        if xs and c != "regex":
            out.append(f"| {c} | {xs[len(xs)//2]:.0f} | {xs[int(0.95*(len(xs)-1))]:.0f} | {len(xs)} |")
    out.append("")

    adapt = os.path.join(R, "adaptive_summary.json")
    if os.path.exists(adapt):
        a = json.load(open(adapt))
        out += [f"## Adaptive attacker (query budget {a['budget']}, "
                f"{next(iter(a['summaries'].values()))['targets']} targets)", "",
                "| guard | targets broken within budget | within 10 | within 20 | median queries to 1st bypass |",
                "|---|---|---|---|---|"]
        for cfg, s in a["summaries"].items():
            lo, hi = s["ci95"]
            out.append(f"| {cfg} | {s['broken_within_budget']}/{s['targets']} "
                       f"(CI {100*lo:.0f}-{100*hi:.0f}%) | {s['broken_within_10']} | "
                       f"{s['broken_within_20']} | {s['median_queries_to_first_success']} |")
        out.append("")
    text = "\n".join(out)
    os.makedirs(os.path.join(HERE, "docs"), exist_ok=True)
    with open(os.path.join(HERE, "docs", "results.md"), "w") as f:
        f.write(text + "\n")
    summ = {f"{c} | {s}": {"attacks": d["att"], "benign": d["ben"]} for (c, s), d in data.items()}
    json.dump(summ, open(os.path.join(R, "final_summary.json"), "w"), indent=2)
    print(text)


if __name__ == "__main__":
    main()
